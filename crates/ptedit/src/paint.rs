/// Glyph cell width and height in font pixels (with spacing).
pub const CELL: (usize, usize) = (6, 9);

impl Canvas<'_> {
    pub fn fill(&mut self, x: i32, y: i32, w: i32, h: i32, c: u32) {
        for yy in y.max(0)..(y + h).min(self.h as i32) {
            for xx in x.max(0)..(x + w).min(self.w as i32) {
                self.px[yy as usize * self.w + xx as usize] = c;
            }
        }
    }

    pub fn rect(&mut self, x0: i32, y0: i32, x1: i32, y1: i32, c: u32) {
        let (x0, x1) = (x0.min(x1), x0.max(x1));
        let (y0, y1) = (y0.min(y1), y0.max(y1));
        self.fill(x0, y0, x1 - x0 + 1, 1, c);
        self.fill(x0, y1, x1 - x0 + 1, 1, c);
        self.fill(x0, y0, 1, y1 - y0 + 1, c);
        self.fill(x1, y0, 1, y1 - y0 + 1, c);
    }

    /// Text with its top-left corner at (`x`, `y`), `scale` screen pixels per font pixel,
    /// on a one-pixel dark shadow.
    pub fn text(&mut self, x: i32, y: i32, s: &str, color: u32, scale: i32) {
        for (pass, c) in [(1, 0x00_0000), (0, color)] {
            for (i, ch) in s.chars().enumerate() {
                let gx = x + i as i32 * CELL.0 as i32 * scale + pass;
                for (row, bits) in glyph(ch).iter().enumerate() {
                    for col in 0..5 {
                        if bits & (0x10 >> col) != 0 {
                            self.fill(gx + col * scale, y + pass + row as i32 * scale, scale, scale, c);
                        }
                    }
                }
            }
        }
    }
}

/// Width in screen pixels of `s` at `scale`.
pub fn text_width(s: &str, scale: i32) -> i32 {
    (s.chars().count() * CELL.0) as i32 * scale - scale
}
