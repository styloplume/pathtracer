//! Direct 2D drawing on a pixel buffer: rectangles and text in an embedded 5x7 bitmap
//! font (view labels, axis letters, the selection rectangle). The UI toolkit (E2) will
//! bring proper fonts.

/// A 0x00RRGGBB buffer `w` pixels wide.
pub struct Canvas<'a> {
    pub px: &'a mut [u32],
    pub w: usize,
    pub h: usize,
}

